static const char* kButtonLabels[8] = {
    "SysSet", "InstSl", "InstAs", "InstFn",
    "VcFn",   "VcSel",  "-1/No",  "+1/Yes"
};

StandaloneGui::~StandaloneGui() {
    close();
}

bool StandaloneGui::open(FB01Emulator* emulator) {
    m_emulator = emulator;

    m_window = SDL_CreateWindow("FB-01 FM Sound Generator",
                                kWindowWidth, kWindowHeight, 0);
    if (!m_window)
        return false;

    m_renderer = SDL_CreateRenderer(m_window, nullptr);
    if (!m_renderer) {
        SDL_DestroyWindow(m_window);
        m_window = nullptr;
        return false;
    }

    return true;
}

void StandaloneGui::close() {
    if (m_renderer) {
        SDL_DestroyRenderer(m_renderer);
        m_renderer = nullptr;
    }
    if (m_window) {
        SDL_DestroyWindow(m_window);
        m_window = nullptr;
    }
}

bool StandaloneGui::processEvents() {
    SDL_Event event;
    while (SDL_PollEvent(&event)) {
        switch (event.type) {
            case SDL_EVENT_QUIT:
                return false;
            case SDL_EVENT_MOUSE_BUTTON_DOWN:
                handleButtonClick(static_cast<int>(event.button.x),
                                  static_cast<int>(event.button.y), true);
                break;
            case SDL_EVENT_MOUSE_BUTTON_UP:
                handleButtonClick(static_cast<int>(event.button.x),
                                  static_cast<int>(event.button.y), false);
                break;
            case SDL_EVENT_KEY_DOWN:
                if (event.key.key == SDLK_ESCAPE)
                    return false;
                break;
            default:
                break;
        }
    }
    // Release buttons that have been held long enough
    updateButtonHold();
    return true;
}

void StandaloneGui::handleButtonClick(int x, int y, bool pressed) {
    if (!pressed) {
        // Mark buttons for deferred release (updateButtonHold handles timing)
        // Don't immediately release — let the minimum hold time elapse
        return;
    }

    if (y < kButtonY || y > kButtonY + kButtonHeight)
        return;

    for (int i = 0; i < 8; i++) {
        int bx = kButtonStartX + i * kButtonSpacing;
        if (x >= bx && x < bx + kButtonWidth) {
            m_buttonPressed[i] = true;
            m_buttonPressTime[i] = SDL_GetTicks();
            // Update button state: active-low (bit = 0 when pressed)
            uint8_t buttons = 0xFF;
            for (int j = 0; j < 8; j++) {
                if (m_buttonPressed[j])
                    buttons &= ~(1 << j);
            }
            m_emulator->setButtonState(buttons);
            break;
        }
    }
}

void StandaloneGui::updateButtonHold() {
    uint32_t now = SDL_GetTicks();
    bool anyChanged = false;
    for (int i = 0; i < 8; i++) {
        if (m_buttonPressed[i] && (now - m_buttonPressTime[i] >= kMinHoldMs)) {
            m_buttonPressed[i] = false;
            anyChanged = true;
        }
    }
    if (anyChanged) {
        uint8_t buttons = 0xFF;
        for (int j = 0; j < 8; j++) {
            if (m_buttonPressed[j])
                buttons &= ~(1 << j);
        }
        m_emulator->setButtonState(buttons);
    }
}

void StandaloneGui::render() {
    // Dark background
    SDL_SetRenderDrawColor(m_renderer, 40, 40, 40, 255);
    SDL_RenderClear(m_renderer);

    renderLCD();
    renderButtons();

    SDL_RenderPresent(m_renderer);
}

void StandaloneGui::renderLCD() {
    // LCD background (dark red)
    SDL_FRect lcdRect = {kLCDX, kLCDY, kLCDWidth, kLCDHeight};
    SDL_SetRenderDrawColor(m_renderer, 30, 0, 0, 255);
    SDL_RenderFillRect(m_renderer, &lcdRect);

    // Get display text from emulator
    const char* text = m_emulator->getLCDText();
    if (!text) return;

    int len = static_cast<int>(strlen(text));
    float cellW = static_cast<float>(kLCDWidth - 20) / 16.0f;
    float cellH = static_cast<float>(kLCDHeight - 10);
    float dotW = cellW / 6.0f;   // 5 dots + 1 gap
    float dotH = cellH / 8.0f;   // 7 dots + 1 gap

    SDL_SetRenderDrawColor(m_renderer, 180, 0, 0, 255);
    for (int i = 0; i < len && i < 16; i++) {
        uint8_t ch = static_cast<uint8_t>(text[i]);
        // Map character to font index (0x20-0x7F supported)
        const uint8_t* glyph;
        if (ch >= 0x20 && ch <= 0x7F) {
            glyph = kFont5x7[ch - 0x20];
        } else {
            // Unmapped characters: show as space
            glyph = kFont5x7[0];
        }

        float cx = kLCDX + 10 + i * cellW;
        float cy = kLCDY + 5;

        for (int row = 0; row < 7; row++) {
            uint8_t rowBits = glyph[row];
            for (int col = 0; col < 5; col++) {
                if (rowBits & (0x10 >> col)) {
                    SDL_FRect dot = {
                        cx + col * dotW,
                        cy + row * dotH,
                        dotW * 0.85f,
                        dotH * 0.85f
                    };
                    SDL_RenderFillRect(m_renderer, &dot);
                }
            }
        }
    }
}

void StandaloneGui::renderButtons() {
    for (int i = 0; i < 8; i++) {
        float bx = static_cast<float>(kButtonStartX + i * kButtonSpacing);
        float by = static_cast<float>(kButtonY);
        SDL_FRect btnRect = {bx, by,
                             static_cast<float>(kButtonWidth),
                             static_cast<float>(kButtonHeight)};

        if (m_buttonPressed[i]) {
            SDL_SetRenderDrawColor(m_renderer, 100, 100, 120, 255);
        } else {
            SDL_SetRenderDrawColor(m_renderer, 70, 70, 80, 255);
        }
        SDL_RenderFillRect(m_renderer, &btnRect);

        // Button border
        SDL_SetRenderDrawColor(m_renderer, 120, 120, 130, 255);
        SDL_RenderRect(m_renderer, &btnRect);

        // Label (simple debug text via SDL_RenderDebugText)
        SDL_SetRenderDrawColor(m_renderer, 200, 200, 200, 255);
        SDL_RenderDebugText(m_renderer, bx + 4, by + 25, kButtonLabels[i]);
    }
}

